/**
 * 从 src/i18n/locales/en.json 生成 overlay 在收到主进程 evp:strings 前的回退文案。
 * npm run build 时自动执行。
 */
const fs = require('node:fs');
const path = require('node:path');

const enPath = path.join(__dirname, '..', 'src', 'i18n', 'locales', 'en.json');
const outPath = path.join(__dirname, '..', 'overlay', 'locale-fallback.js');

const en = JSON.parse(fs.readFileSync(enPath, 'utf8'));
const body = JSON.stringify(en, null, 2);

const content = `/** Auto-generated by scripts/gen-overlay-locale.cjs — do not edit */
(function () {
  globalThis.__evpDefaultStrings = ${body};
})();
`;

fs.writeFileSync(outPath, content, 'utf8');
console.log('wrote overlay/locale-fallback.js');
